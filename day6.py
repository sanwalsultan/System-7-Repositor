import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

data = {
    "Student": ["Ali", "Sara", "Ahmed", "Ayesha", "Usman", "Zara"],
    "Maths": [85, 90, None, 70, 65, 95],
    "Science": [80, None, 75, 85, None, 90],
    "English": [78, 88, 82, None, 72, 94]
}

df = pd.DataFrame(data)

print(df)

print("Missing values in each column:")
print(df.isnull().sum())

plt.figure(figsize=(8, 5))

sns.heatmap(
    df[["Maths", "Science", "English"]].isnull(),
    cbar=False,
    cmap="viridis",
    yticklabels=df["Student"]
)

plt.title("Missing Values Before Cleaning")
plt.xlabel("Subjects")
plt.ylabel("Students")
plt.show()

clean_df = df.copy()

subjects = ["Maths", "Science", "English"]

for subject in subjects:
    clean_df[subject] = clean_df[subject].fillna(
        clean_df[subject].mean()
    )

print("Cleaned Dataset:")
print(clean_df)

print("\nMissing values after cleaning:")
print(clean_df[subjects].isnull().sum())

plt.figure(figsize=(8, 5))

sns.heatmap(
    clean_df[subjects].isnull(),
    cbar=False,
    cmap="viridis",
    yticklabels=clean_df["Student"]
)

plt.title("Missing Values After Cleaning")
plt.xlabel("Subjects")
plt.ylabel("Students")
plt.show()

print("Missing values before cleaning:")
print(df[subjects].isnull().sum().sum())

print("\nMissing values after cleaning:")
print(clean_df[subjects].isnull().sum().sum())

